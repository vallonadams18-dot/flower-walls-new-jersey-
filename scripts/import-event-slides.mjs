/**
 * "Events that Bloomed" slideshow — imports the eleven photographs the old
 * WordPress site ran in its homepage carousel, in the order it ran them.
 *
 *   npm i --no-save sharp
 *   node scripts/import-event-slides.mjs
 *
 * Downloads each original (750x500 PNGs, ~750KB apiece), re-encodes to JPEG
 * into public/legacy/events/, and rewrites src/data/event-slides.ts with the
 * slide list. Slugs and alt text are hand-written from the photographs; the
 * old filenames all said "San-Francisco", because the site was cloned from a
 * California business, so none of them were worth keeping.
 */
import sharp from "sharp";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const BASE = "https://www.flowerwallsnewjersey.com/wp-content/uploads/2024/08/";
const OUT = "public/legacy/events";

/** [ original filename, new slug, alt text ] — carousel order. */
const SLIDES = [
  ["Flower-Wall-Rental-San-Francisco-Slide-1.png", "champagne-pommery-greenery-wall", "Guest in a sequinned gown posing at a white and greenery flower wall lit by a Champagne Pommery neon sign"],
  ["Flower-Wall-Rental-San-Francisco-Slide-3.png", "evanta-corporate-greenery-wall", "Boxwood greenery wall crowned with mixed florals and an illuminated Evanta, a Gartner Company logo"],
  ["Flower-Wall-Rental-San-Francisco-Slide-6.png", "ritz-carlton-blue-flower-wall", "Three guests photographed at a blue and white flower wall beneath a Ritz-Carlton sign"],
  ["Flower-Wall-Rental-San-Francisco-Slide-2.png", "inside-beauty-forum-hedge-wall", "Inside Beauty Forum neon logo mounted on a bright green hedge wall"],
  ["Flower-Wall-Rental-East-Bay.png", "ombre-rose-flower-wall", "Ombre rose wall fading from deep magenta through blush to ivory, styled in a private home"],
  ["Flower-Wall-Rental-San-Francisco-bay-area.png", "wedding-sweetheart-table-floral", "Outdoor wedding sweetheart table with white thrones set against a white floral backdrop"],
  ["Flower-Wall-Rental-San-Francisco-Slide-4.png", "red-pink-garden-rose-wall", "Four guests posing together in front of a red and pink garden rose wall"],
  ["Flower-Wall-Rental-San-Francisco-bay-area.3.png", "blush-rose-wall-neon-bar", "Blush rose wall with a custom pink neon sign behind an event bar"],
  ["Flower-Wall-Rental-San-Francisco-bay-area-2.png", "black-tie-reception-tablescape", "Reception tablescape in black and blush with gold chargers and a dark floral backdrop"],
  ["Flower-Wall-Rental-San-Francisco-bay-area.5.png", "betsey-johnson-pink-rose-wall", "Pink rose wall with a Betsey Johnson neon sign and a hot pink sofa at a trade show booth"],
  ["Flower-Wall-Rental-San-Francisco-Slide-5.png", "wedding-welcome-sign-roses", "Black wedding welcome sign topped with roses at a stone venue entrance"],
];

await mkdir(OUT, { recursive: true });

const slides = [];
for (const [original, slug, alt] of SLIDES) {
  const res = await fetch(BASE + encodeURIComponent(original));
  if (!res.ok) throw new Error(`${original}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  const file = `${slug}.jpg`;
  const info = await sharp(buf)
    .jpeg({ quality: 82, mozjpeg: true, chromaSubsampling: "4:4:4" })
    .toFile(path.join(OUT, file));
  slides.push({ src: `/legacy/events/${file}`, alt, width: info.width, height: info.height });
  console.log(
    file.padEnd(38),
    `${(buf.length / 1024).toFixed(0)}KB -> ${(info.size / 1024).toFixed(0)}KB`,
  );
}

await writeFile(
  "src/data/event-slides.ts",
  `/**
 * "Events that Bloomed" carousel slides. Generated by
 * scripts/import-event-slides.mjs — edit that, not this.
 *
 * The ornate gold frame is part of each photograph, so the slides render
 * without a border of their own.
 */
export interface EventSlide {
  src: string;
  alt: string;
  width: number;
  height: number;
}

export const EVENT_SLIDES: EventSlide[] = ${JSON.stringify(slides, null, 2)};
`,
  "utf8",
);
console.log(`\nwrote src/data/event-slides.ts — ${slides.length} slides`);

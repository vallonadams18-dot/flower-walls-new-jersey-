/**
 * Post-build step. Turns `src/data/redirects.ts` into redirects in ./out.
 *
 * Runs automatically after `npm run build` via the postbuild script.
 *
 * Writes two things:
 *   out/<old-path>/index.html   a meta-refresh + canonical stub. The only
 *                               redirect GitHub Pages can serve, since it
 *                               returns static files and cannot issue a 3xx.
 *   out/_redirects              Cloudflare Pages / Netlify format, which does
 *                               produce real 301s if the host ever changes.
 *
 * Safety: a stub is never written over a real page. If a path in the map has
 * become a genuine route, the stub is skipped and reported, because shadowing
 * a live page with a redirect is a far worse outcome than a missing redirect.
 */
import { mkdir, writeFile, readFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

const OUT = "out";
if (!existsSync(OUT)) {
  console.error("no ./out — run `npm run build` first");
  process.exit(1);
}

// Read the map out of the TS source without needing a TS loader.
const src = await readFile("src/data/redirects.ts", "utf8");
const entries = [
  ...src.matchAll(/from:\s*"([^"]+)",\s*\n\s*to:\s*"([^"]+)",/g),
].map((m) => ({ from: m[1], to: m[2] }));

if (!entries.length) {
  console.error("no redirects parsed from src/data/redirects.ts");
  process.exit(1);
}

const PROD = "https://www.flowerwallsnewjersey.com";

// The canonical is absolute on purpose. A relative canonical resolves against
// whatever host serves the stub, which during the preview period is
// github.io — exactly the wrong signal to send about the destination.
const stub = (to) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved</title>
<link rel="canonical" href="${PROD}${to}">
<meta http-equiv="refresh" content="0; url=${to}">
<script>location.replace(${JSON.stringify(to)} + location.search + location.hash)</script>
</head>
<body>
<p>This page has moved to <a href="${to}">${to}</a>.</p>
</body>
</html>
`;

let written = 0;
const skipped = [];

for (const { from, to } of entries) {
  const dir = path.join(OUT, from.replace(/^\/|\/$/g, ""));
  const file = path.join(dir, "index.html");
  if (existsSync(file)) {
    skipped.push(`${from} — a real page exists there, stub NOT written`);
    continue;
  }
  await mkdir(dir, { recursive: true });
  await writeFile(file, stub(to), "utf8");
  written++;
}

// Cloudflare / Netlify format, generated so it cannot drift from the map above.
const widest = Math.max(...entries.map((e) => e.from.length));
const lines = [
  "# Generated by scripts/write-redirects.mjs from src/data/redirects.ts.",
  "# Do not edit by hand — edit the map and rebuild.",
  "#",
  "# Real 301s on Cloudflare Pages / Netlify. GitHub Pages ignores this file,",
  "# which is why the HTML stubs beside it exist.",
  ...entries.flatMap(({ from, to }) => [
    `${from.padEnd(widest + 2)}${to}  301`,
    // also match the no-trailing-slash form
    `${from.replace(/\/$/, "").padEnd(widest + 2)}${to}  301`,
  ]),
];
await writeFile(path.join(OUT, "_redirects"), lines.join("\n") + "\n", "utf8");

console.log(`redirects: ${written} stubs written, ${entries.length} rules in out/_redirects`);
for (const s of skipped) console.log("  skipped: " + s);
